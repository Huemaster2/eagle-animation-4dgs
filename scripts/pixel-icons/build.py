#!/usr/bin/env python3
# Turns icons16.txt (ASCII pixel art) into the app's FontAwesome-style icon modules in
# src/renderer/icons/. '#' is ink (currentColor, so themes recolour it); 'o' is the icon's
# accent colour, emitted as the duotone secondary layer and coloured per icon by icon-accents.css.
# Usage: python3 scripts/pixel-icons/build.py [--preview out.png]
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
ICONS = HERE.parents[1] / 'src' / 'renderer' / 'icons'
ACCENT_CSS = HERE.parents[1] / 'src' / 'renderer' / 'styles' / 'icon-accents.css'
GRID = 16
NOFILL = set()


def parse(text):
    # Header: '== faName [accent=colour] [nofill]'; nofill keeps enclosed areas open when they hold a drawn mark
    icons, accents, name, rows = {}, {}, None, []
    for line in text.splitlines():
        m = re.match(r'^== (\w+)(?:\s+accent=(\w+))?(\s+nofill)?\s*$', line)
        if m:
            if name:
                icons[name] = rows
            name, rows = m.group(1), []
            if m.group(2):
                accents[name] = m.group(2)
            if m.group(3):
                NOFILL.add(name)
        elif name and line.strip() and set(line.strip()) <= {'#', '.', 'o'}:
            rows.append(line.rstrip())
    if name:
        icons[name] = rows
    return icons, accents


def square(rows):
    w = max(len(r) for r in rows)
    size = max(GRID, w, len(rows))
    top = (size - len(rows)) // 2
    left = (size - w) // 2
    grid = [[0] * size for _ in range(size)]
    for y, r in enumerate(rows):
        for x, c in enumerate(r):
            grid[top + y][left + x] = 1 if c == '#' else 2 if c == 'o' else 0
    return size, grid


def fill_enclosed(grid, min_area=3):
    # Empty cells the outline fully encloses become fill (accent layer), like a System 7 icon's coloured face.
    # Pinholes smaller than min_area stay open so small details (eyes, gaps) survive.
    size = len(grid)
    outside = [[False] * size for _ in range(size)]
    stack = [(x, y) for x in range(size) for y in (0, size - 1)] + [(x, y) for y in range(size) for x in (0, size - 1)]
    while stack:
        x, y = stack.pop()
        if 0 <= x < size and 0 <= y < size and not outside[y][x] and grid[y][x] == 0:
            outside[y][x] = True
            stack += [(x + 1, y), (x - 1, y), (x, y + 1), (x, y - 1)]
    seen = [[False] * size for _ in range(size)]
    for y in range(size):
        for x in range(size):
            if grid[y][x] == 0 and not outside[y][x] and not seen[y][x]:
                region, todo = [], [(x, y)]
                seen[y][x] = True
                while todo:
                    cx, cy = todo.pop()
                    region.append((cx, cy))
                    for nx, ny in ((cx + 1, cy), (cx - 1, cy), (cx, cy + 1), (cx, cy - 1)):
                        if 0 <= nx < size and 0 <= ny < size and not seen[ny][nx] and grid[ny][nx] == 0 and not outside[ny][nx]:
                            seen[ny][nx] = True
                            todo.append((nx, ny))
                if len(region) >= min_area:
                    for cx, cy in region:
                        grid[cy][cx] = 2
    return grid


def layer(grid, value):
    return [[cell == value for cell in row] for row in grid]


def rectangles(grid):
    # Greedy merge: horizontal runs, extended downwards while the run repeats exactly
    size = len(grid)
    used = [[False] * size for _ in range(size)]
    rects = []
    for y in range(size):
        x = 0
        while x < size:
            if grid[y][x] and not used[y][x]:
                x2 = x
                while x2 < size and grid[y][x2] and not used[y][x2]:
                    x2 += 1
                h = 1
                while y + h < size and all(grid[y + h][i] and not used[y + h][i] for i in range(x, x2)):
                    h += 1
                for yy in range(y, y + h):
                    for i in range(x, x2):
                        used[yy][i] = True
                rects.append((x, y, x2 - x, h))
                x = x2
            else:
                x += 1
    return rects


def path_of(rects):
    return ''.join(f'M{x} {y}h{w}v{h}h{-w}z' for x, y, w, h in rects)


def kebab(name):
    return re.sub(r'(?<!^)(?=[A-Z0-9])', '-', name[2:]).lower()


def module(file_name, original, size, path):
    path = f"['{path[0]}', '{path[1]}']" if isinstance(path, tuple) else f"'{path}'"
    prefix = re.search(r"prefix:\s*'([^']+)'", original)
    # Unique per module (FontAwesome names repeat, e.g. star / star-regular), since colours are keyed on it
    icon_name = kebab(file_name)
    return (
        f"// Pixel icon generated by scripts/pixel-icons/build.py from icons16.txt\n"
        f"const {file_name} = {{\n"
        f"  prefix: '{prefix.group(1) if prefix else 'fal'}',\n"
        f"  iconName: '{icon_name}',\n"
        f"  icon: [{size}, {size}, [], 'f000', {path}],\n"
        f"}};\n"
        f"export default {file_name};\n"
    )


def main():
    icons, accents = parse((HERE / 'icons16.txt').read_text())
    previews = []
    css = ['/* Generated by scripts/pixel-icons/build.py: which accent colour each two-tone icon uses */']
    for name, rows in icons.items():
        target = ICONS / f'{name}.js'
        if not target.exists():
            print(f'skip {name}: no such icon module')
            continue
        size, grid = square(rows)
        if name not in NOFILL:
            grid = fill_enclosed(grid)
        original = target.read_text()
        ink = path_of(rectangles(layer(grid, 1)))
        # Icons without a named colour get a neutral 'paper' face
        accent = accents.get(name) or ('paper' if any(2 in row for row in grid) else None)
        if accent:
            # Duotone: [secondary (accent), primary (ink)]
            target.write_text(module(name, original, size, (path_of(rectangles(layer(grid, 2))), ink)))
            css.append(f"svg[data-icon='{kebab(name)}'] {{\n  --pf-accent: var(--pf-accent-{accent});\n}}")
        else:
            target.write_text(module(name, original, size, ink))
        previews.append((name, grid, accent))
    ACCENT_CSS.write_text('\n\n'.join(css) + '\n')
    print(f'{len(previews)} icons written to {ICONS}, {sum(1 for p in previews if p[2])} with a colour fill')
    if '--preview' in sys.argv:
        from PIL import Image, ImageDraw

        out = sys.argv[sys.argv.index('--preview') + 1]
        cols, cell, scale = 8, 120, 4
        sheet = Image.new('RGB', (cols * cell, ((len(previews) + cols - 1) // cols) * cell), 'white')
        d = ImageDraw.Draw(sheet)
        colours = {'yellow': '#f2c230', 'green': '#2fae4e', 'orange': '#ef8a22', 'purple': '#8f52d6', 'paper': '#ffffff'}
        for i, (name, grid, accent) in enumerate(previews):
            ox, oy = (i % cols) * cell + 20, (i // cols) * cell + 6
            for y, row in enumerate(grid):
                for x, on in enumerate(row):
                    if on:
                        fill = 'black' if on == 1 else colours.get(accent, 'gray')
                        d.rectangle([ox + x * scale, oy + y * scale, ox + x * scale + scale - 1, oy + y * scale + scale - 1], fill=fill)
            d.text(((i % cols) * cell + 4, (i // cols) * cell + 100), name[2:][:18], fill='black')
        sheet.save(out)


if __name__ == '__main__':
    main()
