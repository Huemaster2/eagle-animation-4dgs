#!/usr/bin/env python3
# Turns icons16.txt (ASCII pixel art) into the app's FontAwesome-style icon modules in
# src/renderer/icons/. Paths are filled with currentColor, so every theme recolours them.
# Usage: python3 scripts/pixel-icons/build.py [--preview out.png]
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
ICONS = HERE.parents[1] / 'src' / 'renderer' / 'icons'
GRID = 16


def parse(text):
    icons, name, rows = {}, None, []
    for line in text.splitlines():
        if line.startswith('#') and not line.startswith('#.') and not set(line) <= {'#', '.'}:
            continue
        m = re.match(r'^== (\w+)\s*$', line)
        if m:
            if name:
                icons[name] = rows
            name, rows = m.group(1), []
        elif name and line.strip() and set(line.strip()) <= {'#', '.'}:
            rows.append(line.rstrip())
    if name:
        icons[name] = rows
    return icons


def square(rows):
    w = max(len(r) for r in rows)
    size = max(GRID, w, len(rows))
    top = (size - len(rows)) // 2
    left = (size - w) // 2
    grid = [[False] * size for _ in range(size)]
    for y, r in enumerate(rows):
        for x, c in enumerate(r):
            if c == '#':
                grid[top + y][left + x] = True
    return size, grid


def rectangles(grid):
    # Greedy merge: horizontal runs, extended downwards while the run repeats exactly
    size = len(grid)
    used = [[False] * size for _ in range(size)]
    rects = []
    for y in range(size):
        x = 0
        while x < size:
            if grid[y][x] and not used[y][x]:
                x2 = x
                while x2 < size and grid[y][x2] and not used[y][x2]:
                    x2 += 1
                h = 1
                while y + h < size and all(grid[y + h][i] and not used[y + h][i] for i in range(x, x2)):
                    h += 1
                for yy in range(y, y + h):
                    for i in range(x, x2):
                        used[yy][i] = True
                rects.append((x, y, x2 - x, h))
                x = x2
            else:
                x += 1
    return rects


def path_of(rects):
    return ''.join(f'M{x} {y}h{w}v{h}h{-w}z' for x, y, w, h in rects)


def module(file_name, original, size, path):
    prefix = re.search(r"prefix:\s*'([^']+)'", original)
    icon_name = re.search(r"iconName:\s*'([^']+)'", original)
    return (
        f"// Pixel icon generated by scripts/pixel-icons/build.py from icons16.txt\n"
        f"const {file_name} = {{\n"
        f"  prefix: '{prefix.group(1) if prefix else 'fal'}',\n"
        f"  iconName: '{icon_name.group(1) if icon_name else file_name}',\n"
        f"  icon: [{size}, {size}, [], 'f000', '{path}'],\n"
        f"}};\n"
        f"export default {file_name};\n"
    )


def main():
    icons = parse((HERE / 'icons16.txt').read_text())
    previews = []
    for name, rows in icons.items():
        target = ICONS / f'{name}.js'
        if not target.exists():
            print(f'skip {name}: no such icon module')
            continue
        size, grid = square(rows)
        target.write_text(module(name, target.read_text(), size, path_of(rectangles(grid))))
        previews.append((name, grid))
    print(f'{len(previews)} icons written to {ICONS}')
    if '--preview' in sys.argv:
        from PIL import Image, ImageDraw

        out = sys.argv[sys.argv.index('--preview') + 1]
        cols, cell, scale = 8, 120, 4
        sheet = Image.new('RGB', (cols * cell, ((len(previews) + cols - 1) // cols) * cell), 'white')
        d = ImageDraw.Draw(sheet)
        for i, (name, grid) in enumerate(previews):
            ox, oy = (i % cols) * cell + 20, (i // cols) * cell + 6
            for y, row in enumerate(grid):
                for x, on in enumerate(row):
                    if on:
                        d.rectangle([ox + x * scale, oy + y * scale, ox + x * scale + scale - 1, oy + y * scale + scale - 1], fill='black')
            d.text(((i % cols) * cell + 4, (i // cols) * cell + 100), name[2:][:18], fill='black')
        sheet.save(out)


if __name__ == '__main__':
    main()
